#!/usr/bin/env python3
"""
Automatic Beta Version Tracker for Escape From Tartarus.
Format: Beta V.1.<minor>.<patch> where minor = upload_count // 10, patch = upload_count % 10.
Synced automatically from git commit count (+1 for the upcoming upload commit).
"""
import datetime
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
VERSION_JSON_PATH = os.path.join(ROOT, "playtest", "version.json")
VERSION_JS_PATH = os.path.join(ROOT, "playtest", "version.js")
INDEX_HTML_PATH = os.path.join(ROOT, "index.html")


def find_git_bin():
    found = shutil.which("git")
    if found:
        return found
    candidates = [
        r"C:\Program Files\Git\cmd\git.exe",
        r"C:\Program Files\Git\bin\git.exe",
        r"C:\Program Files (x86)\Git\cmd\git.exe",
        os.path.expandvars(r"%LOCALAPPDATA%\Programs\Git\cmd\git.exe"),
    ]
    for path in candidates:
        if os.path.exists(path):
            return path
    return None


def get_git_commit_count():
    git_bin = find_git_bin()
    if not git_bin:
        return None
    try:
        res = subprocess.run(
            [git_bin, "rev-list", "--count", "HEAD"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=10,
        )
        if res.returncode == 0 and res.stdout.strip().isdigit():
            return int(res.stdout.strip())
    except Exception:
        pass
    return None


V2_BASE_UPLOAD = 44


def format_beta_version(upload_count):
    n = max(0, int(upload_count) - V2_BASE_UPLOAD)
    minor = n // 10
    patch = n % 10
    return f"Beta V.2.{minor}.{patch}"


def read_existing_count():
    if not os.path.exists(VERSION_JSON_PATH):
        return 0
    try:
        with open(VERSION_JSON_PATH, "r", encoding="utf-8") as fh:
            data = json.load(fh)
            return int(data.get("uploadCount", 0))
    except Exception:
        return 0


def sync_version(mode="next"):
    git_count = get_git_commit_count()
    existing = read_existing_count()

    if mode == "current":
        upload_count = git_count if git_count is not None else max(1, existing)
    elif mode == "increment":
        base = git_count if git_count is not None else existing
        upload_count = base + 1
    else:
        # Default "next": matches the upcoming GitHub upload commit (git HEAD count + 1)
        if git_count is not None:
            upload_count = git_count + 1
        else:
            upload_count = max(1, existing)

    version_str = format_beta_version(upload_count)
    now_iso = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    v2_n = max(0, upload_count - V2_BASE_UPLOAD)
    payload = {
        "version": version_str,
        "uploadCount": upload_count,
        "major": 2,
        "minor": v2_n // 10,
        "patch": v2_n % 10,
        "updatedAt": now_iso,
    }

    os.makedirs(os.path.dirname(VERSION_JSON_PATH), exist_ok=True)
    with open(VERSION_JSON_PATH, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2)
        fh.write("\n")

    js_content = (
        "// Auto-generated by bump_version.py - DO NOT EDIT MANUALLY\n"
        f"window.EFT_VERSION = {json.dumps(payload, ensure_ascii=False)};\n"
    )
    with open(VERSION_JS_PATH, "w", encoding="utf-8") as fh:
        fh.write(js_content)

    if os.path.exists(INDEX_HTML_PATH):
        with open(INDEX_HTML_PATH, "r", encoding="utf-8") as fh:
            html = fh.read()
        pattern = re.compile(
            r'(<div\b[^>]*class="mts-version-corner"[^>]*>)(.*?)(</div>)',
            re.DOTALL,
        )
        new_html, count = pattern.subn(rf"\g<1>{version_str}\g<3>", html, count=1)
        if count > 0 and new_html != html:
            with open(INDEX_HTML_PATH, "w", encoding="utf-8") as fh:
                fh.write(new_html)

    print(f"[Version] {version_str} (Upload #{upload_count})")
    return payload


if __name__ == "__main__":
    arg = sys.argv[1] if len(sys.argv) > 1 else "--next"
    if arg == "--current":
        sync_version("current")
    elif arg == "--increment":
        sync_version("increment")
    else:
        sync_version("next")
